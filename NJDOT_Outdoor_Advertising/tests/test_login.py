def test_login_invalid_password(page, faker):
    """
    [Negative] Verifies validation error dialog for a valid email with an incorrect password.
    """
    # 1. Initialize Page Objects
    login_page = LoginPage(page)
    
    # 2. Navigate to Login Page
    login_page.load(Config.LOGIN_URL)
    
