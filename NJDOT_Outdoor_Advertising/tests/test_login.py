    login_page = LoginPage(page)
    
    # 2. Navigate to Login Page
    login_page.load(Config.LOGIN_URL)
    
    # 3. Perform Login without credentials
    login_page.login(email="", password="")
    
    # 4. Assert validation errors are visible
    expect(login_page.email_mandatory_error).to_be_visible()
